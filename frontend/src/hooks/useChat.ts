
"use client";

import { useChatContext } from "../context/ChatContext";
import type { ChatMessage } from "../context/ChatContext";
import { sendChatMessage } from "../services/chatService";
import { uploadDocument } from "../services/documentService";

interface ChatApiError {
  response?: {
    data?: {
      detail?: string;
      error?: {
        message?: string;
      };
    };
  };
  message?: string;
}

interface ChatApiResponse {
  success?: boolean;
  answer?: string;
  response?: string;
  message?: string;
  agent_name?: string | null;
  agent_output?: Record<string, unknown> | null;
  status?: string;
}

function getErrorMessage(error: unknown): string {
  if (typeof error === "object" && error !== null) {
    const apiError = error as ChatApiError;

    const message =
      apiError.response?.data?.detail ||
      apiError.response?.data?.error?.message ||
      apiError.message;

    if (typeof message === "string") {
      return message;
    }

    if (message) {
      return JSON.stringify(message);
    }
  }

  return "Unable to connect to the backend. Please check the API server.";
}

function getAIResponse(response: ChatApiResponse): string {
  // Prefer the structured output generated by the AI agent.
  if (response.agent_output) {
    return JSON.stringify(response.agent_output, null, 2);
  }

  // Fall back to the model-generated answer.
  if (typeof response.answer === "string" && response.answer.trim()) {
    return response.answer;
  }

  if (typeof response.response === "string" && response.response.trim()) {
    return response.response;
  }

  if (typeof response.message === "string" && response.message.trim()) {
    return response.message;
  }

  return "The AI did not return an answer.";
}

export default function useChat() {
  const {
    messages,
    setMessages,
    loading,
    setLoading,
    currentDocument,
    setCurrentDocument,
    selectedFile,
    setSelectedFile,
    selectedAgent,
  } = useChatContext();

  const sendMessage = async (message: string): Promise<void> => {
    const text = message?.trim();

    if (!text || loading) return;

    let docId = currentDocument?.document_id || currentDocument?.id;

    if (!docId && !selectedFile) {
      const assistantMessage: ChatMessage = {
        role: "assistant",
        content: "Please select a PDF document first before sending instructions.",
      };

      setMessages((previous) => [...previous, assistantMessage]);
      return;
    }

    const userMessage: ChatMessage = {
      role: "user",
      content: text,
    };

    setMessages((previous) => [...previous, userMessage]);
    setLoading(true);

    try {
      // 1. Upload selected PDF
      if (selectedFile) {
        const uploadResult = await uploadDocument(selectedFile, text);

        docId = uploadResult.document_id || uploadResult.id;

        if (!docId) {
          throw new Error("Document upload did not return a document ID.");
        }

        setCurrentDocument({
          id: String(docId),
          document_id: String(docId),
          name: uploadResult.filename,
          filename: uploadResult.filename,
          storage_path: uploadResult.storage_path,
          instruction: text,
          page_count: uploadResult.page_count ?? null,
          status: "Uploaded",
        });

        setSelectedFile(null);
      }

      if (!docId) {
        throw new Error("Document ID is missing.");
      }

      // 2. Prepare chat history
      const history: ChatMessage[] = messages
        .slice(-12)
        .map((msg) => ({
          role: msg.role === "user" ? "user" : "assistant",
          content: msg.content,
        }));

      // 3. Call Next.js chat API
      const response = (await sendChatMessage(
        text,
        String(docId),
        history,
        selectedAgent || "orchestrator"
      )) as ChatApiResponse;

      console.log("CHAT API RESPONSE:", response);

      if (response.success === false) {
        throw new Error("The AI backend returned an unsuccessful response.");
      }

      // 4. Display actual AI-generated output
      const aiMessage: ChatMessage = {
  role: "assistant",
  agent: response.agent_name || "AI Assistant",
  content: JSON.stringify(response, null, 2),
};

      setMessages((previous) => [...previous, aiMessage]);

    } catch (error: unknown) {
      console.error("Chat API error:", error);

      const aiErrorMessage: ChatMessage = {
        role: "assistant",
        content: getErrorMessage(error),
      };

      setMessages((previous) => [
        ...previous,
        aiErrorMessage,
      ]);

    } finally {
      setLoading(false);
    }
  };

  return {
    messages,
    loading,
    sendMessage,
  };
}
